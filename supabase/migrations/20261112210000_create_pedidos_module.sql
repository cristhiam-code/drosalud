-- Módulo PEDIDOS: solicitudes internas, autorización y generación atómica de órdenes.
-- Ejecutar primero en drosalud-pruebas. No modifica saldos ni movimientos de inventario.

create table public.pedidos (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  tipo text not null check (tipo in ('sugerido','urgente','extraordinario')),
  estado text not null default 'borrador'
    check (estado in ('borrador','pendiente_autorizacion','autorizado','rechazado','cancelado')),
  creado_por uuid not null references auth.users(id) on delete restrict default auth.uid(),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  enviado_en timestamptz,
  autorizado_por uuid references auth.users(id) on delete restrict,
  autorizado_en timestamptz,
  rechazado_por uuid references auth.users(id) on delete restrict,
  rechazado_en timestamptz,
  motivo_rechazo text,
  notas text
);

create table public.pedidos_items (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  producto_id uuid references public.productos(id) on delete set null,
  producto_nombre text not null,
  cantidad_solicitada integer not null check (cantidad_solicitada > 0),
  cantidad_autorizada integer check (cantidad_autorizada is null or cantidad_autorizada >= 0),
  justificacion text,
  costo_estimado numeric check (costo_estimado is null or costo_estimado >= 0),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint pedidos_items_autorizada_no_supera_solicitada
    check (cantidad_autorizada is null or cantidad_autorizada <= cantidad_solicitada)
);

create unique index pedidos_items_producto_unico
  on public.pedidos_items(pedido_id, producto_id)
  where producto_id is not null;
create index pedidos_creado_en_idx on public.pedidos(creado_en desc);
create index pedidos_estado_idx on public.pedidos(estado);
create index pedidos_items_pedido_idx on public.pedidos_items(pedido_id);

alter table public.ordenes_compra
  add column pedido_id uuid references public.pedidos(id) on delete restrict;
alter table public.ordenes_compra_items
  add column pedido_item_id uuid references public.pedidos_items(id) on delete restrict;
create index ordenes_compra_pedido_idx on public.ordenes_compra(pedido_id);
create index ordenes_compra_items_pedido_item_idx on public.ordenes_compra_items(pedido_item_id);

-- Las cotizaciones existentes siguen vinculadas a compras_pendientes.
-- Las nuevas pueden vincularse a una línea de pedido, nunca a ambas.
alter table public.cotizaciones_proveedor
  alter column compra_id drop not null,
  add column pedido_item_id uuid references public.pedidos_items(id) on delete restrict,
  add constraint cotizaciones_proveedor_origen_check
    check ((compra_id is not null) <> (pedido_item_id is not null));
create index cotizaciones_proveedor_pedido_item_idx
  on public.cotizaciones_proveedor(pedido_item_id);

alter table public.pedidos enable row level security;
alter table public.pedidos_items enable row level security;

create policy pedidos_select_equipo
  on public.pedidos for select to authenticated
  using (public.es_usuario_drosalud());

create policy pedidos_items_select_equipo
  on public.pedidos_items for select to authenticated
  using (public.es_usuario_drosalud());

revoke all on public.pedidos, public.pedidos_items from anon, authenticated;
grant select on public.pedidos, public.pedidos_items to authenticated;

create or replace function public.guardar_pedido(
  p_pedido_id uuid,
  p_tipo text,
  p_notas text,
  p_items jsonb
) returns uuid
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_uid uuid := auth.uid();
  v_pedido_id uuid := p_pedido_id;
  v_item jsonb;
  v_item_id uuid;
  v_producto_id uuid;
  v_nombre text;
  v_cantidad integer;
  v_costo numeric;
  v_keep_ids uuid[] := array[]::uuid[];
begin
  if v_uid is null or not public.es_usuario_drosalud() then
    raise exception 'Usuario no autorizado';
  end if;
  if p_tipo not in ('sugerido','urgente','extraordinario') then
    raise exception 'Tipo de pedido inválido';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El pedido debe contener al menos un producto';
  end if;

  if v_pedido_id is null then
    insert into public.pedidos(tipo, notas, creado_por)
    values (p_tipo, nullif(trim(p_notas), ''), v_uid)
    returning id into v_pedido_id;
  else
    perform 1
      from public.pedidos p
     where p.id = v_pedido_id
       and p.estado = 'borrador'
       and (public.es_admin_drosalud() or p.creado_por = v_uid)
     for update;
    if not found then
      raise exception 'El pedido no existe, no está en borrador o no tienes permiso para editarlo';
    end if;
    update public.pedidos
       set tipo = p_tipo, notas = nullif(trim(p_notas), ''), actualizado_en = now()
     where id = v_pedido_id;
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_item_id := nullif(v_item->>'id', '')::uuid;
    v_producto_id := nullif(v_item->>'producto_id', '')::uuid;
    v_cantidad := (v_item->>'cantidad_solicitada')::integer;
    v_costo := nullif(v_item->>'costo_estimado', '')::numeric;

    if v_cantidad is null or v_cantidad <= 0 then
      raise exception 'Todas las cantidades solicitadas deben ser mayores que cero';
    end if;
    if v_costo is not null and v_costo < 0 then
      raise exception 'El costo estimado no puede ser negativo';
    end if;
    if v_producto_id is not null and not exists (
      select 1 from public.productos p where p.id = v_producto_id
    ) then
      raise exception 'Uno de los productos ya no existe en el catálogo';
    end if;

    v_nombre := coalesce(
      nullif(trim(v_item->>'producto_nombre'), ''),
      (select p.nombre from public.productos p where p.id = v_producto_id)
    );
    if v_nombre is null then
      raise exception 'Cada línea debe tener un nombre de producto';
    end if;

    if v_item_id is null then
      v_item_id := gen_random_uuid();
      insert into public.pedidos_items(
        id, pedido_id, producto_id, producto_nombre, cantidad_solicitada,
        justificacion, costo_estimado
      ) values (
        v_item_id, v_pedido_id, v_producto_id, v_nombre, v_cantidad,
        nullif(trim(v_item->>'justificacion'), ''), v_costo
      );
    else
      update public.pedidos_items
         set producto_id = v_producto_id,
             producto_nombre = v_nombre,
             cantidad_solicitada = v_cantidad,
             justificacion = nullif(trim(v_item->>'justificacion'), ''),
             costo_estimado = v_costo,
             actualizado_en = now()
       where id = v_item_id and pedido_id = v_pedido_id;
      if not found then
        raise exception 'Una línea no pertenece a este pedido';
      end if;
    end if;
    if v_item_id = any(v_keep_ids) then
      raise exception 'Una línea está repetida en el pedido';
    end if;
    v_keep_ids := array_append(v_keep_ids, v_item_id);
  end loop;

  if exists (
    select 1
      from public.pedidos_items pi
     where pi.pedido_id = v_pedido_id
       and not (pi.id = any(v_keep_ids))
       and (
         exists (select 1 from public.cotizaciones_proveedor cp where cp.pedido_item_id = pi.id)
         or exists (select 1 from public.ordenes_compra_items oi where oi.pedido_item_id = pi.id)
       )
  ) then
    raise exception 'No puedes quitar una línea que ya tiene cotizaciones u órdenes vinculadas';
  end if;

  delete from public.pedidos_items pi
   where pi.pedido_id = v_pedido_id
     and not (pi.id = any(v_keep_ids));

  return v_pedido_id;
end;
$function$;

create or replace function public.enviar_pedido(p_pedido_id uuid)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null or not public.es_usuario_drosalud() then
    raise exception 'Usuario no autorizado';
  end if;
  if not exists (select 1 from public.pedidos_items where pedido_id = p_pedido_id) then
    raise exception 'No puedes enviar un pedido vacío';
  end if;
  update public.pedidos
     set estado = 'pendiente_autorizacion',
         enviado_en = now(),
         actualizado_en = now()
   where id = p_pedido_id
     and estado = 'borrador'
     and (public.es_admin_drosalud() or creado_por = v_uid);
  if not found then
    raise exception 'El pedido no existe, no está en borrador o no tienes permiso para enviarlo';
  end if;
end;
$function$;

create or replace function public.autorizar_pedido(p_pedido_id uuid, p_items jsonb)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_item jsonb;
  v_item_id uuid;
  v_cantidad integer;
  v_total integer;
  v_actualizados integer := 0;
begin
  if auth.uid() is null or not public.es_admin_drosalud() then
    raise exception 'Solo el administrador puede autorizar pedidos';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Debes indicar las cantidades que autorizas';
  end if;
  perform 1 from public.pedidos where id = p_pedido_id and estado = 'pendiente_autorizacion' for update;
  if not found then
    raise exception 'El pedido no existe o no está pendiente de autorización';
  end if;
  select count(*) into v_total from public.pedidos_items where pedido_id = p_pedido_id;
  if jsonb_array_length(p_items) <> v_total
     or (select count(distinct x.pedido_item_id)
           from jsonb_to_recordset(p_items) as x(pedido_item_id uuid, cantidad_autorizada integer)) <> v_total then
    raise exception 'Debes revisar una sola vez todas las líneas del pedido';
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_item_id := (v_item->>'pedido_item_id')::uuid;
    v_cantidad := (v_item->>'cantidad_autorizada')::integer;
    if v_cantidad is null or v_cantidad < 0 then
      raise exception 'La cantidad autorizada no puede ser negativa';
    end if;
    update public.pedidos_items
       set cantidad_autorizada = v_cantidad, actualizado_en = now()
     where id = v_item_id
       and pedido_id = p_pedido_id
       and v_cantidad <= cantidad_solicitada;
    if not found then
      raise exception 'Una cantidad autorizada supera lo solicitado o una línea no pertenece al pedido';
    end if;
    v_actualizados := v_actualizados + 1;
  end loop;

  if v_actualizados <> v_total or not exists (
    select 1 from public.pedidos_items
     where pedido_id = p_pedido_id and cantidad_autorizada > 0
  ) then
    raise exception 'Debes autorizar al menos una unidad';
  end if;

  update public.pedidos
     set estado = 'autorizado',
         autorizado_por = auth.uid(),
         autorizado_en = now(),
         actualizado_en = now()
   where id = p_pedido_id;
end;
$function$;

create or replace function public.rechazar_pedido(p_pedido_id uuid, p_motivo text)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if auth.uid() is null or not public.es_admin_drosalud() then
    raise exception 'Solo el administrador puede rechazar pedidos';
  end if;
  if nullif(trim(p_motivo), '') is null then
    raise exception 'Escribe el motivo del rechazo';
  end if;
  update public.pedidos
     set estado = 'rechazado',
         rechazado_por = auth.uid(),
         rechazado_en = now(),
         motivo_rechazo = left(trim(p_motivo), 1000),
         actualizado_en = now()
   where id = p_pedido_id and estado = 'pendiente_autorizacion';
  if not found then
    raise exception 'El pedido no existe o no está pendiente de autorización';
  end if;
end;
$function$;

create or replace function public.generar_ordenes_compra_pedido(
  p_pedido_id uuid,
  p_asignaciones jsonb
) returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_provider record;
  v_line record;
  v_order_id uuid;
  v_order_numero bigint;
  v_autorizada integer;
  v_producto_id uuid;
  v_ya_asignado integer;
  v_nuevo integer;
  v_ordenes jsonb := '[]'::jsonb;
begin
  if auth.uid() is null or not public.es_admin_drosalud() then
    raise exception 'Solo el administrador puede generar órdenes de compra';
  end if;
  perform 1 from public.pedidos where id = p_pedido_id and estado = 'autorizado' for update;
  if not found then
    raise exception 'El pedido debe estar autorizado antes de generar órdenes';
  end if;
  if p_asignaciones is null or jsonb_typeof(p_asignaciones) <> 'array'
     or jsonb_array_length(p_asignaciones) = 0 then
    raise exception 'Debes asignar productos a proveedores';
  end if;

  if exists (
    select 1
      from jsonb_to_recordset(p_asignaciones) as a(
        pedido_item_id uuid, proveedor_id uuid, unidades integer, costo_unitario_base numeric
      )
     where a.pedido_item_id is null or a.proveedor_id is null
        or a.unidades is null or a.unidades <= 0
        or a.costo_unitario_base is null or a.costo_unitario_base < 0
  ) then
    raise exception 'Hay asignaciones con proveedor, unidades o costo inválido';
  end if;

  for v_line in
    select a.pedido_item_id, sum(a.unidades)::integer as unidades
      from jsonb_to_recordset(p_asignaciones) as a(
        pedido_item_id uuid, proveedor_id uuid, unidades integer, costo_unitario_base numeric
      )
     group by a.pedido_item_id
  loop
    select pi.cantidad_autorizada, pi.producto_id
      into v_autorizada, v_producto_id
      from public.pedidos_items pi
     where pi.id = v_line.pedido_item_id and pi.pedido_id = p_pedido_id;
    if not found then
      raise exception 'Una línea no pertenece al pedido autorizado';
    end if;
    if v_producto_id is null then
      raise exception 'Vincula todos los productos sin catálogo antes de generar la orden';
    end if;
    if coalesce(v_autorizada, 0) <= 0 then
      raise exception 'La línea no tiene unidades autorizadas';
    end if;

    select coalesce(sum(oi.unidades_solicitadas), 0)::integer
      into v_ya_asignado
      from public.ordenes_compra_items oi
      join public.ordenes_compra oc on oc.id = oi.orden_id
     where oi.pedido_item_id = v_line.pedido_item_id
       and oc.estado <> 'cancelada';

    if v_ya_asignado + v_line.unidades > v_autorizada then
      raise exception 'La suma de órdenes supera las unidades autorizadas para una línea';
    end if;
  end loop;

  for v_provider in
    select distinct a.proveedor_id
      from jsonb_to_recordset(p_asignaciones) as a(
        pedido_item_id uuid, proveedor_id uuid, unidades integer, costo_unitario_base numeric
      )
     order by a.proveedor_id
  loop
    if not exists (
      select 1 from public.proveedores p
       where p.id = v_provider.proveedor_id and p.activo = true
    ) then
      raise exception 'Uno de los proveedores no existe o está inactivo';
    end if;

    insert into public.ordenes_compra(
      pedido_id, proveedor_id, estado, notas, creado_por
    )
    select p_pedido_id, v_provider.proveedor_id, 'aprobada',
           'Generada desde pedido interno #' || p.numero, auth.uid()
      from public.pedidos p
     where p.id = p_pedido_id
    returning id, numero into v_order_id, v_order_numero;

    for v_line in
      select a.pedido_item_id,
             sum(a.unidades)::integer as unidades,
             (sum(a.unidades * a.costo_unitario_base) / sum(a.unidades))::numeric(14,2) as costo
        from jsonb_to_recordset(p_asignaciones) as a(
          pedido_item_id uuid, proveedor_id uuid, unidades integer, costo_unitario_base numeric
        )
       where a.proveedor_id = v_provider.proveedor_id
       group by a.pedido_item_id
    loop
      select pi.producto_id into v_producto_id
        from public.pedidos_items pi
       where pi.id = v_line.pedido_item_id and pi.pedido_id = p_pedido_id;

      insert into public.ordenes_compra_items(
        orden_id, producto_id, unidades_solicitadas, costo_unitario_base, pedido_item_id
      ) values (
        v_order_id, v_producto_id, v_line.unidades, v_line.costo, v_line.pedido_item_id
      );
    end loop;

    v_ordenes := v_ordenes || jsonb_build_array(jsonb_build_object(
      'id', v_order_id, 'numero', v_order_numero, 'proveedor_id', v_provider.proveedor_id
    ));
  end loop;

  return jsonb_build_object('pedido_id', p_pedido_id, 'ordenes', v_ordenes);
end;
$function$;

create or replace view public.pedidos_resumen
with (security_invoker = true)
as
with items as (
  select pedido_id,
         count(*)::integer as lineas,
         coalesce(sum(cantidad_autorizada), 0)::integer as unidades_autorizadas
    from public.pedidos_items
   group by pedido_id
),
ordenes as (
  select pi.pedido_id,
         coalesce(sum(oi.unidades_solicitadas), 0)::integer as unidades_compradas,
         coalesce(sum(oi.unidades_recibidas), 0)::integer as unidades_recibidas
    from public.ordenes_compra_items oi
    join public.ordenes_compra oc on oc.id = oi.orden_id
    join public.pedidos_items pi on pi.id = oi.pedido_item_id
   where oc.estado <> 'cancelada'
   group by pi.pedido_id
)
select p.*,
       coalesce(i.lineas, 0) as lineas,
       coalesce(i.unidades_autorizadas, 0) as unidades_autorizadas,
       coalesce(o.unidades_compradas, 0) as unidades_compradas,
       coalesce(o.unidades_recibidas, 0) as unidades_recibidas,
       case
         when p.estado <> 'autorizado' then p.estado
         when coalesce(i.unidades_autorizadas, 0) > 0
              and coalesce(o.unidades_recibidas, 0) >= i.unidades_autorizadas then 'completado'
         when coalesce(o.unidades_recibidas, 0) > 0 then 'parcialmente_recibido'
         when coalesce(o.unidades_compradas, 0) >= coalesce(i.unidades_autorizadas, 0)
              and coalesce(i.unidades_autorizadas, 0) > 0 then 'en_compra'
         when coalesce(o.unidades_compradas, 0) > 0 then 'parcialmente_comprado'
         else 'autorizado'
       end as estado_operativo
  from public.pedidos p
  left join items i on i.pedido_id = p.id
  left join ordenes o on o.pedido_id = p.id;

grant select on public.pedidos_resumen to authenticated;

-- Cierre de bypass: la creación y aprobación de órdenes independientes también
-- queda reservada al administrador. Los pedidos nuevos usan su RPC de generación.
create or replace function public.crear_orden_compra(
  p_proveedor_id uuid,
  p_items jsonb,
  p_documento text default null,
  p_notas text default null
) returns uuid
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_id uuid;
  v_item jsonb;
  v_producto uuid;
  v_unidades integer;
  v_costo numeric;
begin
  if auth.uid() is null or not public.es_admin_drosalud() then
    raise exception 'Solo el administrador puede crear órdenes de compra';
  end if;
  if not exists(select 1 from public.proveedores where id = p_proveedor_id and activo) then
    raise exception 'Proveedor inexistente o inactivo';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La orden debe contener productos';
  end if;
  insert into public.ordenes_compra(proveedor_id, documento_proveedor, notas, creado_por)
  values (p_proveedor_id, nullif(trim(p_documento), ''), nullif(trim(p_notas), ''), auth.uid())
  returning id into v_id;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_producto := (v_item->>'producto_id')::uuid;
    v_unidades := (v_item->>'unidades_solicitadas')::integer;
    v_costo := (v_item->>'costo_unitario_base')::numeric;
    if v_unidades is null or v_unidades <= 0 or v_costo is null or v_costo < 0 then
      raise exception 'Unidades o costo inválido en orden';
    end if;
    if not exists(select 1 from public.productos where id = v_producto) then
      raise exception 'Producto inexistente en orden';
    end if;
    insert into public.ordenes_compra_items(
      orden_id, producto_id, unidades_solicitadas, costo_unitario_base
    ) values (v_id, v_producto, v_unidades, v_costo);
  end loop;
  return v_id;
end;
$function$;

create or replace function public.aprobar_orden_compra(p_orden_id uuid)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if auth.uid() is null or not public.es_admin_drosalud() then
    raise exception 'Solo el administrador puede aprobar órdenes de compra';
  end if;
  if not exists(select 1 from public.ordenes_compra_items where orden_id = p_orden_id) then
    raise exception 'No se puede aprobar una orden vacía';
  end if;
  update public.ordenes_compra
     set estado = 'aprobada', actualizado_en = now()
   where id = p_orden_id and estado = 'borrador';
  if not found then
    raise exception 'La orden no existe o no está en borrador';
  end if;
end;
$function$;

